use crate::policy::Policy;
use serde::Serialize;
use std::collections::BTreeSet;
use std::path::PathBuf;

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct RenderedFile {
    pub relative_path: PathBuf,
    pub contents: String,
}

#[derive(Debug, thiserror::Error)]
pub enum RenderError {
    #[error("no allow rule contains an exact path to render")]
    NoPaths,
}

/// Render Ubuntu/Debian-style AppArmor default_allow profiles.
///
/// The host must support AppArmor ABI/4.0 userns mediation and the two
/// `kernel.apparmor_restrict_unprivileged_*` sysctls. These profiles deliberately
/// do not try to confine the whole application; they only attach the `userns,`
/// permission while preserving default-allow behavior to reduce browser breakage.
pub fn render_apparmor(policy: &Policy) -> Result<Vec<RenderedFile>, RenderError> {
    let mut seen = BTreeSet::new();
    let mut profiles = String::new();
    let mut count = 0;

    for rule in &policy.allow {
        if !rule.enabled {
            continue;
        }
        for path in &rule.paths {
            let path_str = path.to_string_lossy();
            if !path_str.starts_with('/') || !seen.insert(path_str.to_string()) {
                continue;
            }
            count += 1;
            let profile_name = format!("userns-guard.{}", sanitize_profile_name(&path_str));
            profiles.push_str(&format!(
                r#"# rule: {rule}{categories}
profile "{profile_name}" "{path}" flags=(default_allow) {{
  # Allow user namespace creation only; all other mediation stays in
  # default_allow mode to avoid breaking browser/container behavior.
  userns,
}}
"#,
                rule = rule.name,
                categories = if rule.categories.is_empty() {
                    String::new()
                } else {
                    format!(" ({})", rule.categories.join(", "))
                },
                profile_name = profile_name,
                path = path_str,
            ));
        }
    }

    if count == 0 {
        return Err(RenderError::NoPaths);
    }

    let apparmor = format!(
        "# Generated by userns-guard. Do not edit by hand; update policy.toml instead.\n# Install as /etc/apparmor.d/userns-guard, then run: apparmor_parser -r /etc/apparmor.d/userns-guard\n\nabi <abi/4.0>,\ninclude <tunables/global>\n\n{profiles}"
    );

    let sysctl = r#"# Restrict unprivileged user namespaces for unconfined apps.
# Registered binaries receive userns, through their generated AppArmor profile.
kernel.apparmor_restrict_unprivileged_userns = 1
kernel.apparmor_restrict_unprivileged_unconfined = 1
"#
    .to_string();

    Ok(vec![
        RenderedFile {
            relative_path: PathBuf::from("apparmor.d/userns-guard"),
            contents: apparmor,
        },
        RenderedFile {
            relative_path: PathBuf::from("sysctl.d/99-userns-guard.conf"),
            contents: sysctl,
        },
    ])
}

pub fn sanitize_profile_name(path: &str) -> String {
    let mut out = String::with_capacity(path.len());
    let mut last_dot = false;
    for c in path.trim_start_matches('/').chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c);
            last_dot = false;
        } else if !last_dot {
            out.push('.');
            last_dot = true;
        }
    }
    out.trim_matches('.').to_string()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::presets::preset_policy;

    #[test]
    fn renders_unique_profile_per_path() {
        let files = render_apparmor(&preset_policy()).unwrap();
        let profiles = &files[0].contents;
        assert!(profiles.contains("abi <abi/4.0>"));
        assert!(profiles.contains("/usr/bin/runc"));
        assert!(profiles.contains("/opt/google/chrome/chrome"));
        assert!(profiles.contains("userns,"));
        assert!(files[1]
            .contents
            .contains("apparmor_restrict_unprivileged_userns"));
    }

    #[test]
    fn sanitizes_names() {
        assert_eq!(
            sanitize_profile_name("/opt/google/chrome/chrome"),
            "opt.google.chrome.chrome"
        );
    }
}
